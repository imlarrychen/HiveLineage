package com.panfan.hivelineage;

import com.panfan.hivelineage.core.HiveLineageAnalyzer;
import com.panfan.hivelineage.core.HiveScriptLineageAnalyzer;
import com.panfan.hivelineage.metadata.HiveMetadataCache;
import com.panfan.hivelineage.output.LineageMarkdownRenderer;
import com.panfan.hivelineage.request.LineageAnalyzeOptions;
import com.panfan.hivelineage.request.LineageAnalyzeRequest;
import com.panfan.hivelineage.request.LineageParseMode;
import com.panfan.hivelineage.result.LineageAnalyzeResult;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.Arrays;
import java.util.List;

public final class JoinConditionSnapshot {
    private static final Path SNAPSHOT_FILE = Paths.get("target/lineage-output/join-condition-parse-results.md");

    private JoinConditionSnapshot() {
    }

    public static void main(String[] args) throws Exception {
        Files.write(SNAPSHOT_FILE, render().getBytes(StandardCharsets.UTF_8));
    }

    static String render() {
        StringBuilder builder = new StringBuilder();
        builder.append("# Join Condition Parse Results\n\n")
            .append("> This file is generated by `JoinConditionSnapshot` for manual review.\n\n");

        HiveLineageAnalyzer analyzer = new HiveScriptLineageAnalyzer();
        for (JoinCase joinCase : joinCases()) {
            LineageAnalyzeResult result = analyzer.analyzeScript(LineageAnalyzeRequest.builder()
                .workflowId("wf_join_snapshot")
                .taskId(joinCase.taskId)
                .taskVersion("V1")
                .defaultDatabase("default")
                .metadataProvider(joinMetadataProvider())
                .metadataCache(new HiveMetadataCache())
                .rawScript(joinCase.sql)
                .options(LineageAnalyzeOptions.builder()
                    .parseMode(LineageParseMode.TABLE_AND_COLUMN)
                    .expandViewLineage(true)
                    .includeTemporaryLineage(true)
                    .parseJoinConditions(joinCase.parseJoinConditions)
                    .fallbackVariableValue("fallback_value")
                    .build())
                .build());

            builder.append("## ")
                .append(joinCase.title)
                .append("\n\n")
                .append("### Test SQL\n\n")
                .append("```sql\n")
                .append(joinCase.sql.trim())
                .append("\n```\n\n")
                .append(LineageMarkdownRenderer.render(result, joinCase.title + " Parse Result", "default"))
                .append("\n");
        }
        return builder.toString();
    }

    private static List<JoinCase> joinCases() {
        return Arrays.asList(
            new JoinCase(
                "join_default_off",
                "默认关闭 parseJoinConditions 时纯查询 Join 被忽略",
                "select * from ods.t1 a left join ods.t2 b on a.id = b.id;",
                false
            ),
            new JoinCase(
                "join_pure_query",
                "纯查询 Left Join",
                "select * from ods.t1 a left join ods.t2 b on a.id = b.id;",
                true
            ),
            new JoinCase(
                "join_expression",
                "函数表达式 Join",
                "select a.log_id, b.meta_name\n"
                    + "from ods_op_logs a\n"
                    + "left join dim_meta_info b\n"
                    + "on split(a.biz_trace_id, '_')[1] = cast(b.meta_id as string)\n"
                    + "where a.dt = '20260710' and b.dt = '20260710';",
                true
            ),
            new JoinCase(
                "join_unqualified_columns",
                "未带别名字段通过元数据归属",
                "select * from ods.join_left l\n"
                    + "join ods.join_right r on user_id = manager_id;",
                true
            ),
            new JoinCase(
                "join_consecutive",
                "连续 Join",
                "select * from ods.a a\n"
                    + "join ods.b b on a.id = b.id\n"
                    + "left join ods.c c on b.cid = c.id and c.dt = '20260710';",
                true
            ),
            new JoinCase(
                "join_implicit_where",
                "隐式 Where 关联不作为 JoinCondition",
                "select * from ods.a a, ods.b b where a.id = b.id;",
                true
            ),
            new JoinCase(
                "join_exists_subquery",
                "Exists 子查询内显式 Join",
                "select * from ods.a a join ods.b b on a.id = b.id\n"
                    + "where exists (\n"
                    + "  select 1 from ods.c c join ods.d d on c.id = d.id\n"
                    + "  where c.id = a.id\n"
                    + ");",
                true
            ),
            new JoinCase(
                "join_cte_physical_trace",
                "CTE Join 追溯到物理表字段",
                "with x as (\n"
                    + "  select a.id as id from ods.a a join ods.b b on a.id = b.id\n"
                    + "), y as (\n"
                    + "  select c.id as id from ods.c c join ods.d d on c.id = d.id\n"
                    + ")\n"
                    + "select * from x join y on x.id = y.id;",
                true
            ),
            new JoinCase(
                "join_cte_unresolved",
                "CTE 字段无法唯一追溯",
                "with x as (\n"
                    + "  select * from ods.a a join ods.b b on a.id = b.id\n"
                    + "), y as (\n"
                    + "  select id from ods.c\n"
                    + ")\n"
                    + "select * from x join y on x.id = y.id;",
                true
            ),
            new JoinCase(
                "join_temporary_table",
                "临时表 Join 追溯到物理表字段",
                "create temporary table tmp_user as\n"
                    + "select user_id, dept_id from ods.user_base;\n"
                    + "select * from tmp_user t join dim.dept d on t.dept_id = d.dept_id;",
                true
            )
        );
    }

    private static TestMetadataProvider joinMetadataProvider() {
        return GeneratedSqlTestSetTest.generatedMetadataProvider()
            .addTable("ods.join_left", "user_id", "name")
            .addTable("ods.join_right", "manager_id", "dept_name");
    }

    private static final class JoinCase {
        private final String taskId;
        private final String title;
        private final String sql;
        private final boolean parseJoinConditions;

        private JoinCase(String taskId, String title, String sql, boolean parseJoinConditions) {
            this.taskId = taskId;
            this.title = title;
            this.sql = sql;
            this.parseJoinConditions = parseJoinConditions;
        }
    }
}
